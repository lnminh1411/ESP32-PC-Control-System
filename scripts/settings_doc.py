"""
Writes docs/settings-reference.md: every setting in
firmware/main/settings_or_example.h with its default and its note, one table
per section of that file. Only the defaults file is read (never settings.h),
and the secrets section at its top is left out, so nothing private ends up in
the page. Run it after adding or changing a setting:

    python scripts/settings_doc.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULTS = os.path.join(ROOT, "firmware", "main", "settings_or_example.h")
OUT = os.path.join(ROOT, "docs", "settings-reference.md")

SECTION = re.compile(r"^// ---- (.+?) ----\s*$")
DEFINE = re.compile(r"^#define\s+([A-Z0-9_]+)\s+(.*?)\s*(?://\s*(.*))?$")
SKIP_SECTION = "secrets"


def cell(text):
    return text.replace("|", "\\|").strip()


def main():
    sections = []
    pending = []          # comment lines just above an #ifndef, for keys with no note of their own
    with open(DEFAULTS, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            m = SECTION.match(line)
            if m:
                sections.append((m.group(1), []))
                pending = []
                continue
            if not sections:
                continue
            if line.startswith("//"):
                pending.append(line[2:].strip())
                continue
            m = DEFINE.match(line)
            if m:
                key, value, note = m.group(1), m.group(2), m.group(3) or " ".join(pending)
                if not note and sections[-1][1]:
                    note = "(as above)"   # a run of keys shares the first one's note
                sections[-1][1].append((key, value, note))
                pending = []
            elif not line.startswith("#ifndef") and not line.startswith("#endif"):
                pending = []

    body = []
    total = 0
    for name, keys in sections:
        if name.lower().startswith(SKIP_SECTION) or not keys:
            continue
        body += [f"## {name[0].upper() + name[1:]}", "", "| Key | Default | Note |", "|---|---|---|"]
        for key, value, note in keys:
            body.append(f"| `{key}` | `{cell(value)}` | {cell(note)} |")
            total += 1
        body.append("")
    out = [
        "# Settings reference",
        "",
        "Generated by `python scripts/settings_doc.py` from",
        "[firmware/main/settings_or_example.h](../firmware/main/settings_or_example.h);",
        "don't edit by hand. Each of these %d keys can be overridden in `settings.h`." % total,
        "The secrets are described in [settings.md](settings.md).",
        "",
    ] + body
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out).rstrip("\n") + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {total} keys")


if __name__ == "__main__":
    main()
