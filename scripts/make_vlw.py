"""
Convert a TrueType/OpenType font to LovyanGFX's smooth (anti-aliased) VLW
format and write it as a C++ source with a const byte array.

VLW layout (all int32 big-endian), as parsed by LovyanGFX's VLWfont:
  header  : glyph count, version (11), size, 0, ascent, descent
  glyphs  : per glyph unicode, height, width, xAdvance, dY (top above
            baseline), dX (left offset), 0 -- sorted by unicode
  bitmaps : per glyph width*height bytes of 8-bit alpha, same order

    python scripts/make_vlw.py FONT.otf SIZE NAME OUT.cpp [--extra U+00B0,U+F2C9]

The default charset is printable ASCII plus the degree and micro signs. LovyanGFX
stores code points in 16 bits, so --extra glyphs must be in the BMP
(Nerd Font's older icon sets are; the U+F0000 MDI range is not).
"""
import argparse
import os
import struct

from PIL import ImageFont

DEFAULT_CHARS = [*range(0x20, 0x7F), 0xB0, 0xB5]


def parse_extra(s):
    out = []
    for part in filter(None, (p.strip() for p in s.split(","))):
        cp = int(part[2:] if part.upper().startswith("U+") else part, 16)
        if cp > 0xFFFF:
            raise SystemExit(f"U+{cp:X} is outside the BMP; LovyanGFX VLW cannot index it")
        out.append(cp)
    return out


def build_vlw(path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    records, bitmaps = [], []
    for cp in sorted(set(chars)):
        ch = chr(cp)
        adv = round(font.getlength(ch))
        mask, (ox, oy) = font.getmask2(ch, mode="L")   # anchored at the ascender line
        w, h = mask.size
        if w == 0 or h == 0:
            w = h = 0
            data = b""
        else:
            data = bytes(mask)
        dy = ascent - oy                              # top of bitmap above the baseline
        records.append(struct.pack(">7i", cp, h, w, adv, dy, ox, 0))
        bitmaps.append(data)
    header = struct.pack(">6i", len(records), 11, size, 0, ascent, descent)
    return header + b"".join(records) + b"".join(bitmaps), ascent, descent


def write_cpp(blob, name, out, src, size):
    lines = [f"// Generated by scripts/make_vlw.py from {os.path.basename(src)} at {size} px -- do not edit.",
             "#include <stdint.h>", "",
             f"extern const uint8_t {name}[] = {{"]
    for i in range(0, len(blob), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 20]) + ",")
    lines += ["};", f"extern const uint32_t {name}_len = {len(blob)};", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description="TTF/OTF -> LovyanGFX VLW C array")
    ap.add_argument("font")
    ap.add_argument("size", type=int, help="pixel size (em)")
    ap.add_argument("name", help="C identifier of the array")
    ap.add_argument("out", help="output .cpp")
    ap.add_argument("--extra", default="", help="extra code points, e.g. U+F2C9,U+F108")
    args = ap.parse_args()
    blob, asc, desc = build_vlw(args.font, args.size, DEFAULT_CHARS + parse_extra(args.extra))
    write_cpp(blob, args.name, args.out, args.font, args.size)
    print(f"{args.name}: {len(blob)} bytes, ascent {asc}, descent {desc}")


if __name__ == "__main__":
    main()
