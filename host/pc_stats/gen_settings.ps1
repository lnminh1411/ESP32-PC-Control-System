# Writes Settings.g.cs: the HOST_* keys of the firmware's settings, as C#
# constants of class HostSettings (prefix dropped: HOST_NIGHT_CORES ->
# HostSettings.NIGHT_CORES). Defaults come from settings_or_example.h, then
# settings.h (or settings_example.h when there is none) overrides them, the
# same way the firmware build picks its values. Only HOST_* lines are read,
# so no secret reaches the exe. Run by build.cmd before dotnet publish.
$ErrorActionPreference = 'Stop'
$main = Join-Path $PSScriptRoot '..\..\firmware\main'
$defaults = Join-Path $main 'settings_or_example.h'
$settings = Join-Path $main 'settings.h'
if (-not (Test-Path $settings)) { $settings = Join-Path $main 'settings_example.h' }

# #define HOST_NAME value   // comment   (value: a "C string", a number, true/false)
$re = '^\s*#define\s+HOST_([A-Z0-9_]+)\s+("(?:[^"\\]|\\.)*"|[^/\s]+)'
$values = [ordered]@{}
foreach ($file in @($defaults, $settings)) {
  foreach ($line in [IO.File]::ReadAllLines($file)) {
    $m = [regex]::Match($line, $re)
    if ($m.Success) { $values[$m.Groups[1].Value] = $m.Groups[2].Value }
  }
}

$out = New-Object System.Collections.Generic.List[string]
$out.Add('// Generated by gen_settings.ps1 from firmware/main/settings*.h. Do not edit.')
$out.Add('static partial class HostSettings {')
foreach ($name in $values.Keys) {
  $v = $values[$name]
  if ($v.StartsWith('"')) { $type = 'string' }                              # C escapes are C# escapes
  elseif ($v -eq 'true' -or $v -eq 'false') { $type = 'bool' }
  elseif ($v -match '^-?\d+$') { $type = 'int' }
  elseif ($v -match '^-?(\d+\.\d*|\.\d+)([eE][-+]?\d+)?$') { $type = 'double' }
  else { throw "settings: HOST_$name = $v is not a string, number or true/false" }
  $out.Add("  public const $type $name = $v;")
}
$out.Add('}')
$target = Join-Path $PSScriptRoot 'Settings.g.cs'
$text = ($out -join "`r`n") + "`r`n"
# rewrite only on change, so an unchanged settings.h doesn't force a recompile
if (-not (Test-Path $target) -or [IO.File]::ReadAllText($target) -ne $text) {
  [IO.File]::WriteAllText($target, $text, (New-Object System.Text.UTF8Encoding($false)))
}
Write-Host "settings: $($values.Count) HOST_* keys from $(Split-Path $settings -Leaf)"
